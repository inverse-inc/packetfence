package Catalyst::Plugin::Session::State::MAC;

=head1 NAME

Catalyst::Plugin::Session::State::MAC

=cut

=head1 DESCRIPTION

Overrides the cookie session state in order to keep use the MAC as the real session ID while keeping the cookie session ID as well

=cut

use Moose;
use namespace::autoclean;
use pf::util;

extends 'Catalyst::Plugin::Session::State::Cookie';

our $VERSION = "0.01";

=head2 get_session_id

Get the session ID for the session
In our case, if there is a MAC we use it
Otherwise we take the value in the session cookie
If all fails we generate a session ID

=cut

sub get_session_id {
    my $c = shift;

    my $mac = $c->portalSession->clientMac;
    if(valid_mac($mac)){
        $mac =~ s/\://g;
        return $mac;
    }
    # Allow to restore the session from a RelayState for the SSO callbacks
    elsif(defined(my $relay_state = $c->relay_state_session_id())) {
        $c->stash->{browser_session_id} = $relay_state;
        $c->stash->{browser_session_id_from_relay_state} = 1;
        return $relay_state;
    }
    else {
        my $sid = $c->browser_session_id();
        return $sid;
    }
};

=head2 update_session_cookie

Update the session cookie by making sure we put the browser_session_id in it instead of the MAC address
A browser session ID restored from a RelayState is not written in the cookie: the browser already has it

=cut

sub update_session_cookie {
    my ( $c, $updated ) = @_;

    unless ( $c->cookie_is_rejecting( $updated ) ) {
        # a browser session ID restored from a RelayState is not written
        return if $c->stash->{browser_session_id_from_relay_state};
        return if !$c->stash->{browser_session_id} && defined($c->relay_state_session_id());
        my $browser_session_id = $c->browser_session_id();
        my $cookie_name = $c->_session_plugin_config->{cookie_name};
        # We create the cookie using the browser_session_id which will contain a previously created session ID
        $c->response->cookies->{$cookie_name} = $c->make_session_cookie($browser_session_id);
    }
};

=head2 browser_session_id

Get the browser session ID (not tied to MAC address)

=cut

sub browser_session_id {
    my ($c) = @_;
    if($c->stash->{browser_session_id}) {
        return $c->stash->{browser_session_id};
    }
    elsif(defined(my $relay_state = $c->relay_state_session_id())) {
        $c->stash->{browser_session_id} = $relay_state;
        $c->stash->{browser_session_id_from_relay_state} = 1;
        return $relay_state;
    }
    elsif($c->request->cookie('CGISESSION')){
        return $c->request->cookie('CGISESSION')->value();
    }
    else {
        $c->stash->{browser_session_id} = $c->generate_session_id();
        return $c->stash->{browser_session_id};
    }
}

=head2 relay_state_session_id

The browser session ID given in the RelayState parameter: only on the SSO
callbacks (SAML assertion and MFA), where the browser session ID is sent in
the RelayState since the browser may not send its cookie, and only when it
has the format of a session ID generated by Catalyst::Plugin::Session

=cut

my %RELAY_STATE_PATHS = map { $_ => 1 } qw(saml/assertion mfa);

sub relay_state_session_id {
    my ($c) = @_;
    my $relay_state = $c->request->{parameters}->{RelayState};
    return undef if !defined($relay_state) || ref($relay_state);
    my $path = $c->request->path // '';
    $path =~ s#^/+##;
    $path =~ s#/+$##;
    return undef if !$RELAY_STATE_PATHS{$path};
    return undef if $relay_state !~ /\A[0-9a-f]{32,64}\z/i;
    return $relay_state;
}


