#!/usr/bin/perl

=head1 NAME

kafka-init -

=head1 DESCRIPTION

kafka-init

=cut

use strict;
use warnings;
use lib qw(/usr/local/pf/lib);
use lib qw(/usr/local/pf/lib_perl/lib/perl5);
use pf::file_paths qw($kafka_config_file);
use pf::IniFiles;
use pf::cluster qw($cluster_enabled @cluster_hosts %ConfigCluster);
use pfconfig::manager;
use Crypt::OpenSSL::Random;
use MIME::Base64;
use Data::UUID;

my $ini = pf::IniFiles->new(-file => $kafka_config_file);
my $changed = 0;
my @setup_values = (
    {
        section => 'admin',
        param => 'pass',
        default_val => '%admin_password%',
        new_val => sub {
            return unpack("H*", Crypt::OpenSSL::Random::random_bytes(16));
        }
    },
    {
        section => 'auth client',
        param => 'pass',
        default_val => '%client_password%',
        new_val => sub {
            return unpack("H*", Crypt::OpenSSL::Random::random_bytes(16));
        }
    },
    {
        section => 'ssl',
        param => 'keystore_password',
        default_val => '%keystore_password%',
        new_val => sub {
            return unpack("H*", Crypt::OpenSSL::Random::random_bytes(16));
        }
    },
    {
        section => 'ssl',
        param => 'truststore_password',
        default_val => '%truststore_password%',
        new_val => sub {
            return unpack("H*", Crypt::OpenSSL::Random::random_bytes(16));
        }
    },
    {
        section => 'cluster',
        param => 'CLUSTER_ID',
        default_val => '%uuid%',
        new_val => sub {
            my $uuid = Data::UUID->new->create_bin();
            my $cluster_id =  encode_base64($uuid, '');
            $cluster_id =~ tr|+/=|\-_|d;
            return $cluster_id;
        }
    },

);

sub get_kafka_config() {
    return {%ConfigCluster{@cluster_hosts}}
}

# Ensure the [ssl] section exists with its static defaults so a node upgraded
# from a kafka.conf that predates mTLS gets a complete section. The two password
# entries are generated by the @setup_values loop below; the rest are inert
# defaults (mTLS stays disabled until configured from the admin UI).
my %ssl_defaults = (
    enabled      => 'disabled',
    ca_id        => '',
    profile_id   => '',
    cn           => '',
    dns_names    => '',
    ip_addresses => '',
    peer_ca      => '',
    listener     => 'EXTERNAL',
);
for my $param (sort keys %ssl_defaults) {
    next if $ini->exists('ssl', $param);
    $ini->newval('ssl', $param, $ssl_defaults{$param});
    $changed |= 1;
}

for my $setup (@setup_values) {
    my ($section, $param) = ($setup->{section}, $setup->{param});
    my $val = $ini->val($section, $param);
    # (Re)generate the secret when the key is absent (older configs predate a
    # section), still empty, or still carries its %placeholder% default.
    next if defined $val && $val ne '' && $val ne $setup->{default_val};
    if ($ini->exists($section, $param)) {
        $ini->setval($section, $param, $setup->{new_val}->());
    } else {
        $ini->newval($section, $param, $setup->{new_val}->());
    }
    $changed |= 1;
}

my %keep = map { $_ => 1 } ('cluster', 'admin', 'auth client', 'iptables', 'ssl') ;

if ($cluster_enabled) {
    for my $section ($ini->Sections) {
        next if exists $keep{$section} || $section =~ /^auth /;
        $changed |= 1;
        $ini->DeleteSection($section);
    }

    my @cluster_members = get_cluster_member_for_kafka();
    my $quorum_voters = make_quorum_voters(\@cluster_members);
    my $factor = int((scalar @cluster_members )/ 2) + 1;
    set_or_create($ini, 'cluster', 'KAFKA_OFFSETS_TOPIC_REPLICATION_FACTOR', $factor);
    set_or_create($ini, 'cluster', 'KAFKA_CONTROLLER_QUORUM_VOTERS', $quorum_voters);
    my @ips;
    for my $cluster_member (@cluster_members) {
        push @ips, $cluster_member->{mgmtip};
        my $id = $cluster_member->{host};
        set_or_create($ini, $id, 'KAFKA_NODE_ID', $cluster_member->{node_id});
        set_or_create($ini, $id, 'KAFKA_ADVERTISED_LISTENERS', $cluster_member->{advertised_listeners});
    }

    set_or_create($ini, 'iptables', 'cluster_ips', join(",", @ips));
    set_or_create($ini, 'iptables', 'clients', join(",", @ips));
}

sub get_cluster_member_for_kafka {
    my @members;
    my $config = get_kafka_config();
    my $i = 0;
    for my $k (sort keys %$config) {
        $i++;
        my $val = $config->{$k};
        push @members, make_member(
            $val->{host},
            $val->{management_ip}, $i
        );
    }

    return @members;
}

sub make_member {
    my ($host, $ip, $node_id) = @_;
    # In a cluster, every broker must advertise a unique, cross-node routable
    # address for the PF listener. Using containers-gateway.internal here makes
    # all brokers advertise the same hostname, which resolves to each node's own
    # local broker -- so clients can never reach a partition leader / group
    # coordinator that lives on another node (Not Leader / Not Coordinator
    # errors). Advertise the node's management IP, like INTERNAL/EXTERNAL do.
    my $advertised_listeners = qq{INTERNAL://${ip}:29092,EXTERNAL://${ip}:9092,PF://${ip}:9095,PFCONNECTOR://127.0.0.1:9096};
    return {
        host => $host,
        node_id => $node_id,
        mgmtip => $ip,
        advertised_listeners => $advertised_listeners,
    };
}

sub make_quorum_voters {
    my ($members) = @_;
    return join(",", map { "$_->{node_id}\@$_->{mgmtip}:9093" } @$members);
}

sub set_or_create {
    my ($ini, $section, $param, $val) = @_;
    $changed |= 1;
    if ($ini->exists($section, $param)) {
        $ini->setval($section, $param, $val);
    } else {
        $ini->newval($section, $param, $val);
    }
}

if ($changed) {
    $ini->RewriteConfig();
    # We edited kafka.conf directly on disk, so the pfconfig cache for this
    # namespace is now stale. Expire it so that downstream consumers
    # (e.g. `pfcmd service kafka generateconfig` building var/conf/kafka.env)
    # read the values we just wrote instead of the previous cached ones.
    pfconfig::manager->new->expire("config::Kafka");
}

